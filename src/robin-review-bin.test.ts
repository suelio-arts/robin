fs.writeFileSync(process.env.FAKE_ENGINE_DUMP, JSON.stringify({ inputs, cwd: process.cwd() }));
const plan = JSON.parse(process.env.FAKE_ENGINE_PLAN || "{}");
if (plan.exitCode) process.exit(plan.exitCode);
const lines = Object.entries(plan.outputs || {}).map(([key, value]) => key + "<<EOF\\n" + value + "\\nEOF");
