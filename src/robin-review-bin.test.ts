const marker = (
  outcome: string,
  head: string,
  counts?: [number, number, number, number],
): string => {
  const tail = counts
    ? ` high=${counts[0]} medium=${counts[1]} low=${counts[2]} suggestions=${counts[3]}`
    : "";
  return `<!-- robin-outcome: v1 ${outcome} head=${head}${tail} -->`;
};

